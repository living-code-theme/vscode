export function generate(flavors) {
  return [...flavors.flatMap(f => vscode.files(f)), ...(vscode.all?.(flavors) ?? [])].filter(f => !["LICENSE", "README.md", "package.json", "extension.toml"].includes(f.path.split("/").at(-1)));
}
